export function localCompanionReply(text: string, userName: string): { body: string; verseId?: string } {
  const n = normalizeText(text);
  const conscience = analyze(text);

  if (conscience.categories.includes("crisis")) {
    return {
      body: `${userName} عزیز، حرفت را شنیدم و برایم خیلی مهمی 🤍 لطفاً همین حالا با کسی حرف بزن: اورژانس اجتماعی ۱۲۳ (شبانه‌روزی)، صدای مشاور ۱۴۸۰، و اگر در خطر فوری هستی اورژانس ۱۱۵. تو تنها نیستی و خدا از تو ناامید نیست:`,
      verseId: "39:53",
    };
  }
  if (["راهنما", "کمک", "help", "منو"].includes(n)) return { body: HELP };
  if (/^(یه |یک )?آیه( بده| بفرست)?$/.test(n) || n === "ayah") {
    const v = randomVerse();
    return { body: "این آیه امروز برای توست ✨", verseId: v.id };
  }
  if (n.length < 25 && /(^| )(سلام|درود|hi|hello|salam)( |$)/.test(n)) {
    return {
      body: `سلام ${userName} عزیز 🌙 خوش آمدی. امروز حالت چطور است؟ هر چه در دلت هست بنویس. این هم آیهٔ امروز:`,
      verseId: verseOfTheDay().id,
    };
  }
  if (n.length < 30 && /(ممنون|مرسی|متشکر|سپاس|thanks)/.test(n)) {
    return { body: "خواهش می‌کنم عزیزم 🌸 شکر اصلی از آنِ خداست:", verseId: "14:7" };
  }

  let best: Topic | null = null;
  let bestScore = 0;
  for (const t of TOPICS) {
    let score = 0;
    for (const k of t.keys) if (n.includes(normalizeText(k))) score += k.length;
    if (score > bestScore) {
      best = t;
      bestScore = score;
    }
  }
  if (best) return { body: pick(best.intros), verseId: pick(best.verses) };
  return { body: pick(DEFAULT_INTROS), verseId: randomVerse().id };
}
